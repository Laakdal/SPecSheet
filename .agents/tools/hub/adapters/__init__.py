"""Platform adapters. Each module exposes generate(project) -> list[Output].

To support a new platform: add a module here with generate(), register it in
ADAPTERS, add its id to model.PLATFORMS, and add scenario expectations
(see docs/guides/add-platform.md).
"""
import posixpath
import re
from dataclasses import dataclass


@dataclass
class Output:
    path: str      # posix path relative to project root
    content: object  # str or bytes
    source: str    # source path this was generated from


def md_header(source: str) -> str:
    return f"<!-- generated by hub from {source}; edit the source and run hub sync -->\n"


def hash_header(source: str) -> str:
    return f"# generated by hub from {source}; edit the source and run hub sync\n"


_LINK = re.compile(r"(\[[^\]\n]*\]\()([^)\s]+)(\))")
_CODE = re.compile(r"(^(```|~~~)[\s\S]*?^\2[^\n]*$|`[^`\n]*`)", re.M)


def relink(text: str, src_rel: str, dst_rel: str, keep_within: str = None) -> str:
    """Rewrite relative Markdown links so they still resolve from dst_rel.
    Links inside code spans/fences, URL/anchor links, and links that stay
    inside `keep_within` (a directory copied alongside) are untouched."""
    src_dir = posixpath.dirname(src_rel)
    dst_dir = posixpath.dirname(dst_rel)
    if src_dir == dst_dir:
        return text

    def fix(m):
        target = m.group(2)
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith(("#", "/", "<")) or "{{" in target:
            return m.group(0)
        path, sep, frag = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(src_dir, path))
        if keep_within and (resolved + "/").startswith(keep_within.rstrip("/") + "/"):
            return m.group(0)
        new = posixpath.relpath(resolved, dst_dir or ".")
        return m.group(1) + new + sep + frag + m.group(3)

    out, pos = [], 0
    for c in _CODE.finditer(text):
        out.append(_LINK.sub(fix, text[pos:c.start()]))
        out.append(c.group(0))
        pos = c.end()
    out.append(_LINK.sub(fix, text[pos:]))
    return "".join(out)


def with_md_header(text: str, source: str) -> str:
    """Insert the header after frontmatter (if any) so frontmatter stays first."""
    import fm
    block, body = fm.split(text)
    if block is None:
        return md_header(source) + text
    return "---\n" + block + "\n---\n" + md_header(source) + body


def capability(meta) -> str:
    return meta.get("capability", "edit")


def comma(paths) -> str:
    if isinstance(paths, str):
        return paths
    return ",".join(paths or [])


def as_list(paths):
    if isinstance(paths, str):
        return [p.strip() for p in paths.split(",") if p.strip()]
    return list(paths or [])


