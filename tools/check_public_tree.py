"""Refuse game content in commits.

This repository is public, and ETS2's files (archives, models, textures,
definitions, shaders) belong to SCS Software: the app loads them from the
user's install at runtime and never ships them.

Usage:
    python tools/check_public_tree.py          check the files staged for commit (the pre-commit hook)
    python tools/check_public_tree.py --all    check every file git would track (tracked + untracked, not ignored)

Enable the hook once per clone:  git config core.hooksPath .githooks
"""

import subprocess
import sys

MAX_BYTES = 5 * 1024 * 1024  # nothing we write is this large; extracted game content often is
SCAN_BYTES = 256 * 1024  # how much of each file the content checks read

GAME_EXTENSIONS = (
    ".scs", ".pmd", ".pmg", ".pma", ".pmc", ".ppd", ".dds", ".tobj",
    ".mat", ".sii", ".sui", ".fso", ".vso", ".rfx",
)

# File signatures at offset 0. Our own sources mention these strings, but never start with them.
MAGIC = (
    (b"SCS#", "HashFS archive (SCS#)"),
    (b"SHDO", "compiled game shader (SHDO)"),
    (b"DDS ", "DDS texture"),
    (b"SiiNunit", "game SII definition"),
    (b"ScsC", "encrypted game SII definition"),
    (b"\x15gmP", "PMG geometry"),
    (b"# This file was generated by deployfx", "game effect interface (deployfx)"),
)


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], check=True, capture_output=True).stdout


def staged_paths() -> list[str]:
    out = git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z")
    return [p for p in out.decode("utf-8").split("\0") if p]


def all_paths() -> list[str]:
    out = git("ls-files", "-z", "--cached", "--others", "--exclude-standard")
    return [p for p in out.decode("utf-8").split("\0") if p]


def read_staged(paths: list[str]) -> dict[str, tuple[int, bytes]]:
    """Size and leading bytes of each staged blob, through one `git cat-file --batch`."""
    request = "".join(f":{p}\n" for p in paths).encode("utf-8")
    out = subprocess.run(
        ["git", "cat-file", "--batch"], input=request, check=True, capture_output=True
    ).stdout
    blobs, pos = {}, 0
    for path in paths:
        end = out.index(b"\n", pos)
        header = out[pos:end].split()
        pos = end + 1
        if len(header) < 3 or header[1] == b"missing":
            continue
        size = int(header[2])
        blobs[path] = (size, out[pos : pos + min(size, SCAN_BYTES)])
        pos += size + 1  # content, then a newline
    return blobs


def read_worktree(paths: list[str]) -> dict[str, tuple[int, bytes]]:
    blobs = {}
    for path in paths:
        try:
            with open(path, "rb") as f:
                head = f.read(SCAN_BYTES)
                f.seek(0, 2)
                blobs[path] = (f.tell(), head)
        except (FileNotFoundError, IsADirectoryError):
            continue
    return blobs


def reason(path: str, size: int, head: bytes) -> str | None:
    lower = path.lower()
    if lower.startswith("research/extracted/") or "/extracted/" in lower:
        return "extracted game content (keep it in the gitignored research/extracted/)"
    if lower.endswith(GAME_EXTENSIONS):
        return "game file type (build test fixtures in code instead)"
    for magic, what in MAGIC:
        if head.startswith(magic):
            return what
    # Shader source pulled out of effect.scs: GLSL from the game's generator.
    if (head.startswith(b"#version ") or b"\n#version " in head) and b"cg_TexCoord" in head:
        return "game shader source (GLSL from effect.scs)"
    if size > MAX_BYTES:
        return f"larger than 5 MiB ({size} bytes)"
    return None


def main() -> int:
    check_all = "--all" in sys.argv[1:]
    paths = all_paths() if check_all else staged_paths()
    blobs = read_worktree(paths) if check_all else read_staged(paths)
    failures = [
        f"  {path}: {why}"
        for path, (size, head) in blobs.items()
        if (why := reason(path, size, head))
    ]
    if failures:
        print("check_public_tree: refusing game content in a public repository:", file=sys.stderr)
        print("\n".join(failures), file=sys.stderr)
        print(
            "Unstage these files (git restore --staged <path>). "
            "The app loads game data from the user's install.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
